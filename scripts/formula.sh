#!/usr/bin/env bash
# Prints the Homebrew formula for a published release, from the checksums GitHub keeps for
# its archives: scripts/formula.sh 0.3.0 > ../homebrew-tap/Formula/den.rb
set -euo pipefail

version="${1:?usage: scripts/formula.sh VERSION}"
tag="v$version"
base="https://github.com/fran0x/den/releases/download/$tag"

sha() {
    local digest
    digest=$(gh release view "$tag" --repo fran0x/den --json assets \
        -q ".assets[] | select(.name == \"den-$tag-$1.tar.gz\") | .digest")
    [[ "$digest" =~ ^sha256:[0-9a-f]{64}$ ]] || { echo "no checksum for $1 in $tag" >&2; exit 1; }
    echo "${digest#sha256:}"
}

cat <<EOF
# Generated by scripts/formula.sh in fran0x/den; edit that script, not this file.
class Den < Formula
  desc "Terminal inspector for developer machines, read-only by default"
  homepage "https://github.com/fran0x/den"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
      url "$base/den-$tag-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "$base/den-$tag-x86_64-apple-darwin.tar.gz"
      sha256 "$(sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "$base/den-$tag-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "$(sha aarch64-unknown-linux-gnu)"
    end
    on_intel do
      url "$base/den-$tag-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "$(sha x86_64-unknown-linux-gnu)"
    end
  end

  def install
    bin.install "den", "dew"
  end

  test do
    assert_match "den #{version}", shell_output("#{bin}/den --version")
    assert_match "dew #{version}", shell_output("#{bin}/dew --version")
  end
end
EOF
